-- Email verification and password reset with 6-digit codes.
-- Existing accounts are marked verified so nobody is locked out; new sign-ups start unverified.
ALTER TABLE users ADD COLUMN email_verified BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE users ALTER COLUMN email_verified SET DEFAULT FALSE;

-- At most one live code per user per purpose (VERIFY_EMAIL or RESET_PASSWORD).
-- Only a BCrypt hash of the code is stored, never the code itself.
CREATE TABLE email_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    purpose VARCHAR(20) NOT NULL,
    code_hash VARCHAR(255) NOT NULL,
    attempts INT NOT NULL DEFAULT 0,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_email_codes_user_purpose UNIQUE (user_id, purpose)
);
