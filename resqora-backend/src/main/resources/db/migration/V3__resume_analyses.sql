CREATE TABLE resume_analyses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resume_id BIGINT NOT NULL UNIQUE,
    overall_score INT NOT NULL,
    completeness_score INT NOT NULL,
    skills_score INT NOT NULL,
    projects_score INT NOT NULL,
    experience_score INT NOT NULL,
    education_score INT NOT NULL,
    findings_json TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_resume_analyses_resume FOREIGN KEY (resume_id) REFERENCES resumes(id) ON DELETE CASCADE
);
