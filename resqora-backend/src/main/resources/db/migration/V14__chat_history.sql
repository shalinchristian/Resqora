CREATE TABLE chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    resume_id BIGINT REFERENCES resumes(id) ON DELETE CASCADE,
    scope VARCHAR(20) NOT NULL CHECK (scope IN ('DASHBOARD', 'RESUME')),
    role VARCHAR(20) NOT NULL CHECK (role IN ('user', 'assistant')),
    content TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_chat_scope CHECK (
        (scope = 'DASHBOARD' AND resume_id IS NULL) OR
        (scope = 'RESUME' AND resume_id IS NOT NULL)
    )
);

CREATE INDEX idx_chat_messages_history ON chat_messages (user_id, scope, resume_id, created_at, id);
